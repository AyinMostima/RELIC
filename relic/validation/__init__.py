# Convenience function for quick validation

def quick_validate(state_manager=None, layers=None, domains=None):
    """
    Quick validation helper for interactive use.

    Parameters
    ----------
    state_manager : StateManager, optional
        State manager to validate.
    layers : List[str], optional
        Validation layers to run (default: ["L1", "L2"]).
    domains : List[str], optional
        Domains to validate (default: all).

    Returns
    -------
    ValidationReportModel
        Validation report generated by ValidationEngine.

    Examples
    --------
    >>> from relic.validation import quick_validate
    >>> report = quick_validate(layers=["L1", "L2"])
    >>> print(report.to_markdown())
    """
    if layers is None:
        layers = ["L1", "L2"]

    engine = ValidationEngine()
    context = ValidationContext(state_manager=state_manager)
    return engine.run(layers=layers, domains=domains, context=context)
